#!/usr/bin/env python3
"""Generate public Markdown from the site's rendered, semantic HTML.

Build sequence (run from the repository root):
  python3 -m pip install -r scripts/requirements-agents.txt
  bundle exec jekyll build
  python3 scripts/build_agent_markdown.py
  bundle exec jekyll build
  python3 scripts/build_agent_markdown.py --check --check-rendered

The second Jekyll build publishes agent-markdown/*.txt at their index.md
permalinks. These are Jekyll pages, NOT Markdown inputs: layout:null and a .txt
extension prevent Markdown-to-HTML conversion. Do not exclude agent-markdown.
No plugins or modifications to article sources are needed on GitHub Pages.

Only complete pairs in _data/translations.yml are exported. --check compares
deterministic generated sources, including a hash of extracted semantic content
and metadata. Navigation, resource cache-busters and build time are excluded.
--check-rendered additionally compares the published Markdown byte for byte.
--only /canonical/path/ is useful for an isolated smoke test; it never deletes
other files or rewrites the full route manifest. --output can target a temporary
directory. A normal full run removes only stale page-*.txt generated by this
script. Publication and modification dates always come from the source page.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote, unquote, urljoin, urlsplit

try:
    import yaml
    from bs4 import BeautifulSoup, Comment, NavigableString, Tag
except ImportError as error:
    raise SystemExit("Install scripts/requirements-agents.txt first: " + str(error))

ROOT = Path(__file__).resolve().parents[1]
GENERATOR_VERSION = 1
BLOCKS = {"main", "article", "section", "div", "header", "footer", "aside",
          "figure", "figcaption", "details", "summary", "p", "dl", "address"}
REMOVED = ("script, style, template, form, button, input, select, textarea, "
           "[hidden], [aria-hidden='true'], [data-toc], .sr-only, "
           ".hero-art, .hero-note, .topic-strip, .filter-status, "
           ".technical-search-status, .library-status, .technical-empty, "
           ".library-empty, .filter-empty, .guide-empty")


def compact_text(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def md_text(value: str) -> str:
    """Escape literal text, never source code or URLs."""
    value = re.sub(r"\s+", " ", value)
    return re.sub(r"([\\`*_\[\]<>])", r"\\\1", value)


def absolute_url(base: str, value: str) -> str:
    url = urljoin(base, value)
    if urlsplit(url).scheme not in {"http", "https", "mailto", "tel"}:
        return ""
    # Angle-bracket destinations tolerate parentheses; percent-encode spaces,
    # literal angle brackets and quotes without double-encoding existing URLs.
    return quote(url, safe=":/?#[]@!$&'()*+,;=%~._-")


def md_link(label: str, url: str) -> str:
    return f"[{label}](<{url}>)" if url else label


def markdown_path(canonical_path: str) -> str:
    return canonical_path.rstrip("/") + "/index.md"


def html_file(site: Path, route: str) -> Path:
    path = site / unquote(urlsplit(route).path).lstrip("/")
    candidates = [path / "index.html", path, Path(str(path) + ".html")]
    for candidate in candidates:
        if candidate.is_file():
            if site.resolve() not in candidate.resolve().parents:
                raise ValueError(f"Source escapes site directory: {route}")
            return candidate
    raise ValueError(f"Missing built HTML for {route}: {candidates}")


def schema_nodes(soup: BeautifulSoup) -> list[dict]:
    nodes = []
    for script in soup.select('script[type="application/ld+json"]'):
        value = json.loads(script.get_text())
        if isinstance(value, dict):
            nodes.extend(value.get("@graph", [value]))
        elif isinstance(value, list):
            nodes.extend(value)
    return nodes


@dataclass
class CodePiece:
    token: str
    text: str
    markdown: str
    block: bool


class MarkdownRenderer:
    """Small semantic renderer with lossless, separately protected code."""

    def __init__(self, canonical: str, lang: str):
        self.canonical = canonical
        self.lang = lang
        self.codes: list[CodePiece] = []

    def children(self, node: Tag) -> str:
        classes = node.get("class", [])
        separator = " " if any(css.endswith("-meta") or css in {
            "hero-actions", "app-card-top", "guide-byline"} for css in classes) else ""
        return separator.join(self.render(child) for child in node.children)

    def code(self, node: Tag, block: bool) -> str:
        # BeautifulSoup concatenates Rouge span text without inserting spaces.
        text = node.get_text()
        longest = max((len(x) for x in re.findall(r"`+", text)), default=0)
        if block:
            fence = "`" * max(3, longest + 1)
            language = ""
            for tag in [node, node.find("code"), node.parent]:
                if isinstance(tag, Tag):
                    for css in tag.get("class", []):
                        if css.startswith("language-"):
                            candidate = css[len("language-"):]
                            if re.fullmatch(r"[A-Za-z0-9_+.-]+", candidate):
                                language = candidate
            markdown = fence + language + "\n" + text
            if not text.endswith("\n"):
                markdown += "\n"
            markdown += fence
        else:
            fence = "`" * max(1, longest + 1)
            pad = " " if text.startswith(("`", " ")) or text.endswith(("`", " ")) else ""
            markdown = fence + pad + text + pad + fence
        token = f"\x00AGENT_CODE_{len(self.codes)}\x00"
        self.codes.append(CodePiece(token, text, markdown, block))
        return "\n\n" + token + "\n\n" if block else token

    def render(self, node) -> str:
        if isinstance(node, Comment):
            return ""
        if isinstance(node, NavigableString):
            return md_text(str(node))
        if not isinstance(node, Tag):
            return ""
        name = node.name
        if name == "pre":
            return self.code(node, True)
        if name == "code":
            return self.code(node, False)
        if name in {"script", "style", "source", "track"}:
            return ""
        if name == "br":
            return "  \n"
        if name == "hr":
            return "\n\n---\n\n"
        if name == "video":
            label = "视频" if self.lang == "zh-CN" else "Video"
            links = []
            sources = [node] if node.get("src") else node.find_all("source", src=True)
            for source in sources:
                links.append(md_link(label, absolute_url(self.canonical, source["src"])))
            for track in node.find_all("track", src=True):
                title = track.get("label") or track.get("srclang") or "Subtitles"
                links.append(md_link(md_text(title), absolute_url(self.canonical, track["src"])))
            if node.get("poster"):
                links.append(md_link("Poster", absolute_url(self.canonical, node["poster"])))
            return "\n\n" + "\n\n".join(links) + "\n\n"
        if name in {"iframe", "audio"}:
            return "\n\n" + md_link(md_text(node.get("title", name)),
                                     absolute_url(self.canonical, node.get("src", ""))) + "\n\n"
        if name == "img":
            alt = node.get("alt", "")
            if not alt and not node.find_parent(attrs={"data-article-body": True}):
                return ""
            src = absolute_url(self.canonical, node.get("src", ""))
            return f"![{md_text(alt)}](<{src}>)" if src else ""
        if name == "a":
            if node.has_attr("data-video-chapter"):
                label = " ".join(self.render(child).strip() for child in node.children if str(child).strip())
            else:
                label = self.children(node).strip()
            return md_link(label, absolute_url(self.canonical, node.get("href", ""))) if label else ""
        if name in {"ul", "ol"}:
            items = []
            start = int(node.get("start", 1)) if name == "ol" else 1
            for index, item in enumerate(node.find_all("li", recursive=False)):
                value = self.children(item).strip()
                prefix = f"{start + index}. " if name == "ol" else "- "
                lines = value.splitlines()
                if lines:
                    items.append(prefix + lines[0] + "".join("\n" + " " * len(prefix) + line for line in lines[1:]))
            return "\n\n" + "\n".join(items) + "\n\n"
        if name == "table":
            rows = []
            for row in node.find_all("tr"):
                cells = []
                for cell in row.find_all(["th", "td"], recursive=False):
                    text = self.children(cell).strip().replace("|", "\\|")
                    cells.append(re.sub(r"\s*\n+\s*", "<br>", text))
                if cells:
                    rows.append(cells)
            if not rows:
                return ""
            width = max(len(row) for row in rows)
            lines = ["| " + " | ".join(row + [""] * (width - len(row))) + " |" for row in rows]
            lines.insert(1, "| " + " | ".join(["---"] * width) + " |")
            return "\n\n" + "\n".join(lines) + "\n\n"
        content = self.children(node)
        if name in {"h1", "h2", "h3", "h4", "h5", "h6"}:
            return "\n\n" + "#" * int(name[1]) + " " + content.strip() + "\n\n"
        if name in {"strong", "b"}:
            return "**" + content.strip() + "**" if content.strip() else ""
        if name in {"em", "i"}:
            return "*" + content.strip() + "*" if content.strip() else ""
        if name in {"del", "s"}:
            return "~~" + content.strip() + "~~"
        if name == "blockquote":
            return "\n\n" + "\n".join("> " + line for line in content.strip().splitlines()) + "\n\n"
        if name == "dt":
            return "\n\n**" + content.strip() + "**\n\n"
        if name == "dd":
            return content.strip() + "\n\n"
        if name in BLOCKS:
            return "\n\n" + content.strip() + "\n\n" if content.strip() else ""
        return content

    def finish(self, root: Tag) -> str:
        # Compare every original block and inline code node in DOM order with
        # those actually rendered. This catches dropped/duplicated code even if
        # an article has two identical examples.
        expected = [(node.get_text(), node.name == "pre") for node in root.find_all(["pre", "code"])
                    if node.name == "pre" or not node.find_parent("pre")]
        value = self.render(root)
        actual = [(piece.text, piece.block) for piece in self.codes]
        if expected != actual:
            raise ValueError(f"Code coverage mismatch in {self.canonical}")
        value = re.sub(r"(?m)^[ \t]+$", "", value)
        value = re.sub(r"\n{3,}", "\n\n", value).strip() + "\n"
        for piece in self.codes:
            if value.count(piece.token) != 1:
                raise ValueError(f"Code placeholder lost or repeated in {self.canonical}")
            # Lists/quotes add Markdown indentation around a code block. Apply
            # that prefix to each line, without changing the code payload.
            pattern = r"(?m)^([ >\t]*)" + re.escape(piece.token) + r"$"
            match = re.search(pattern, value) if piece.block else None
            if match:
                prefix = match.group(1)
                def prefixed(line):
                    if line.strip():
                        return prefix + line
                    # On empty code lines, list indentation can otherwise
                    # become literal spaces in GFM's fenced-code payload.
                    quote_prefix = prefix.rstrip()
                    return quote_prefix + (" " if quote_prefix and line else "") + line
                replacement = "\n".join(prefixed(line) for line in piece.markdown.split("\n"))
                value = value[:match.start()] + replacement + value[match.end():]
            else:
                value = value.replace(piece.token, piece.markdown)
        return value


def semantic_root(soup: BeautifulSoup, is_article: bool) -> Tag:
    main = soup.find("main")
    if main is None:
        raise ValueError("Source HTML has no main element")
    if is_article:
        root = BeautifulSoup("<main></main>", "html.parser").main
        selectors = (".article-lede, .technical-lede, .technical-credit, "
                     ".translation-note, .technical-history, .work-player, [data-article-body]")
        selected = main.select(selectors)
        selected_ids = {id(node) for node in selected}
        for node in selected:
            # Do not append a matched descendant twice.
            if not any(id(parent) in selected_ids for parent in node.parents if parent is not main):
                root.append(copy.deepcopy(node))
        if not root.select_one("[data-article-body]"):
            raise ValueError("Article has no data-article-body")
    else:
        root = copy.deepcopy(main)
        for node in root.find_all("h1"):
            node.decompose()
    for node in root.select(REMOVED):
        node.decompose()
    for node in list(root.find_all("nav")):
        if "video-chapters" not in node.get("class", []) and not node.find_parent(attrs={"data-article-body": True}):
            node.decompose()
    for node in list(root.find_all("aside")):
        if "technical-history" not in node.get("class", []) and not node.find_parent(attrs={"data-article-body": True}):
            node.decompose()
    # Noscript chapter instructions duplicate the visible chapter list and
    # describe the HTML player, not this static reading representation.
    for node in root.select(".video-chapters noscript, .video-links"):
        node.decompose()
    return root


def liquid_safe(markdown: str) -> str:
    # A source example may itself explain Liquid endraw. Close the raw region,
    # emit that exact token as a quoted Liquid string, then resume the region.
    def escape_endraw(match):
        # Liquid tokenizes tag openings even inside quoted output strings, so
        # emit the opening brace separately instead of quoting a whole tag.
        return "{% endraw %}{{ '{' }}" + match.group(0)[1:] + "{% raw %}"
    return "{% raw %}" + re.sub(r"{%-?\s*endraw\s*-?%}", escape_endraw, markdown) + "{% endraw %}"


@dataclass
class Export:
    route: str
    md_route: str
    source: str
    markdown: str
    filename: str
    code_blocks: int
    inline_codes: int
    article: bool


def export_page(site: Path, route: str, pair: dict) -> Export:
    soup = BeautifulSoup(html_file(site, route).read_text(encoding="utf-8"), "html.parser")
    canonical_tag = soup.select_one('link[rel="canonical"]')
    if canonical_tag is None:
        raise ValueError(f"No canonical for {route}")
    canonical = canonical_tag["href"]
    if unquote(urlsplit(canonical).path) != unquote(route):
        raise ValueError(f"Canonical mismatch: {route} / {canonical}")
    lang = soup.html.get("lang", "")
    if lang not in {"zh-CN", "en"}:
        raise ValueError(f"Unexpected language {lang!r}: {route}")
    heading = soup.select_one("main h1")
    if heading is None:
        raise ValueError(f"No visible title: {route}")
    title = compact_text(heading.get_text(" ", strip=True))
    nodes = schema_nodes(soup)
    article = next((x for x in nodes if x.get("@type") == "BlogPosting"), None)
    root = semantic_root(soup, article is not None)
    renderer = MarkdownRenderer(canonical, lang)
    content = renderer.finish(root)
    origin = urlsplit(canonical).scheme + "://" + urlsplit(canonical).netloc
    translations = {language: origin + pair[key] for language, key in [("zh-CN", "zh_url"), ("en", "en_url")]}
    metadata = {"title": title, "language": lang, "canonical": canonical, "translations": translations}
    en = lang == "en"
    lines = ["# " + md_text(title), "", ("Language: " if en else "语言：") + lang,
             ("Canonical: " if en else "原文：") + md_link(md_text(title), canonical),
             "中文：" + md_link("中文 HTML", translations["zh-CN"]),
             "English: " + md_link("English HTML", translations["en"])]
    if article:
        for key, label in [("datePublished", "Published" if en else "发布于"),
                           ("dateModified", "Modified" if en else "内容更新于")]:
            if article.get(key):
                metadata[key] = article[key]
                lines.append(label + ": " + article[key])
        if article.get("author"):
            metadata["author"] = article["author"]
            authors = article["author"] if isinstance(article["author"], list) else [article["author"]]
            labels = []
            for author in authors:
                if isinstance(author, dict):
                    labels.append(md_link(md_text(author.get("name", "")), author.get("url", "")))
                else:
                    labels.append(md_text(str(author)))
            lines.append(("Author: " if en else "署名：") + ", ".join(labels))
    markdown = "\n".join(lines) + "\n\n" + content
    semantic_hash = hashlib.sha256(json.dumps(
        {"metadata": metadata, "content": content}, ensure_ascii=False, sort_keys=True,
        separators=(",", ":")).encode("utf-8")).hexdigest()
    md_route = markdown_path(route)
    frontmatter = {"layout": None, "permalink": unquote(md_route), "sitemap": False, "noindex": True,
                   "lang": lang, "title": title, "agent_source_url": canonical,
                   "agent_source_sha256": semantic_hash, "agent_generator_version": GENERATOR_VERSION}
    source = "---\n" + yaml.safe_dump(frontmatter, allow_unicode=True, sort_keys=False) + "---\n" + liquid_safe(markdown) + "\n"
    filename = "page-" + hashlib.sha256(route.encode()).hexdigest()[:20] + ".txt"
    return Export(route, md_route, source, markdown + "\n", filename,
                  sum(piece.block for piece in renderer.codes), sum(not piece.block for piece in renderer.codes), article is not None)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--site", type=Path, default=ROOT / "_site", help="Latest full Jekyll HTML build")
    parser.add_argument("--output", type=Path, default=ROOT / "agent-markdown", help="Generated Jekyll source directory")
    parser.add_argument("--manifest", type=Path, default=ROOT / "_data/translations.yml")
    parser.add_argument("--check", action="store_true", help="Read-only: fail on missing, stale or extra generated sources")
    parser.add_argument("--check-rendered", action="store_true", help="Also verify published index.md bytes in --site")
    parser.add_argument("--only", action="append", default=[], help="Canonical path to smoke-test; repeatable")
    args = parser.parse_args()
    pairs = yaml.safe_load(args.manifest.read_text(encoding="utf-8"))
    routes = {}
    for key, pair in pairs.items():
        if pair.get("status") != "complete":
            continue
        if pair.get("zh_url") != key:
            raise ValueError(f"Translation key does not match zh_url: {key}")
        for language_key in ["zh_url", "en_url"]:
            route = pair[language_key]
            if not route.startswith("/") or "?" in route or "#" in route or route in routes:
                raise ValueError(f"Invalid or duplicate canonical route: {route}")
            routes[route] = pair
    selected = args.only or sorted(routes)
    if unknown := set(selected) - set(routes):
        raise ValueError(f"Paths are not complete translation entries: {sorted(unknown)}")
    exports = [export_page(args.site, route, routes[route]) for route in selected]
    expected = {item.filename: item.source for item in exports}
    if not args.only:
        expected["manifest.json"] = json.dumps({"version": 1, "routes": {
            item.route: item.md_route for item in exports}}, ensure_ascii=False, indent=2) + "\n"
    problems = []
    changed = 0
    if not args.check:
        args.output.mkdir(parents=True, exist_ok=True)
    for name, text in expected.items():
        path = args.output / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            if args.check:
                problems.append(f"Missing or stale: {path}")
            else:
                path.write_text(text, encoding="utf-8")
                changed += 1
    if not args.only:
        for path in sorted(args.output.glob("page-*.txt")):
            if path.name not in expected:
                if args.check:
                    problems.append(f"Stale route source: {path}")
                else:
                    path.unlink()
                    changed += 1
    if args.check_rendered:
        for item in exports:
            published = args.site / unquote(item.md_route).lstrip("/")
            if not published.is_file() or published.read_text(encoding="utf-8") != item.markdown:
                problems.append(f"Missing or non-matching published Markdown: {published}")
    articles = sum(item.article for item in exports)
    print(f"{len(exports)} pages ({articles} articles, {len(exports) - articles} entry pages); "
          f"{sum(item.code_blocks for item in exports)} code blocks and "
          f"{sum(item.inline_codes for item in exports)} inline code nodes preserved; "
          f"{changed} files changed")
    if problems:
        for problem in problems[:20]:
            print(problem, file=sys.stderr)
        if len(problems) > 20:
            print(f"... and {len(problems) - 20} more", file=sys.stderr)
        return 1
    print("Generated sources are current." if args.check else "Markdown sources generated.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, KeyError, OSError) as error:
        print(f"Error: {error}", file=sys.stderr)
        raise SystemExit(1)
